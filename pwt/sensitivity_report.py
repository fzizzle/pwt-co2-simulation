"""Generate Study B figures, report tables and a five-slide review draft.

    python -m pwt.sensitivity_report

Requires requirements-study-b.txt. Figures use dashboard.theme's light palette.
The report's recorded choices above the generated marker are preserved.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from pwt.catalog import POWERTRAIN_NAMES
from pwt.sensitivity import BASE, HERE, check_baseline, export, sensitivity
from pwt.sweep import CYCLES

FACTOR_NAMES = {
    "mass": "Car mass", "drag": "Drag coefficient", "rolling": "Rolling resistance",
    "gears": "Gear ratios", "engine": "Peak engine efficiency",
}
PANELS = (
    ("combustion", (("petrol", "wltc"), ("hybrid", "wltc"))),
    ("electric", (("bev", "nedc"), ("bev", "wltc"))),
    ("plugin", (("phev", "franco_eco_generated"), ("phev", "franco_sport_generated"))),
)
MARKER = "<!-- Generated by python -m pwt.sensitivity_report; edit the generator below this point. -->"


def plot(ranked: pd.DataFrame, selection: tuple, path: Path) -> None:
    """Bars join signed endpoint deltas; markers preserve direction and nonlinearity."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    from dashboard.theme import LIGHT

    fig, axes = plt.subplots(1, 2, figsize=(13, 4.8), layout="constrained")
    selected = pd.concat([ranked[(ranked.powertrain == p) & (ranked.cycle == c)]
                          for p, c in selection])
    bound = selected[["delta_low", "delta_high"]].abs().to_numpy().max() * 1.25
    for ax, (powertrain, cycle) in zip(axes, selection):
        own = ranked[(ranked.powertrain == powertrain) & (ranked.cycle == cycle)]
        own = own.sort_values("rank")
        colour = LIGHT.for_powertrain(powertrain)
        for y, row in enumerate(own.itertuples()):
            low, high = sorted((row.delta_low, row.delta_high))
            ax.barh(y, high - low, left=low, height=0.5, color=colour, alpha=0.8)
            ax.scatter(row.delta_low, y, color=colour, marker="o", s=45,
                       edgecolors=LIGHT.text_primary, linewidths=0.6, zorder=3)
            ax.scatter(row.delta_high, y, color=colour, marker="D", s=40,
                       edgecolors=LIGHT.text_primary, linewidths=0.6, zorder=3)
            # Endpoint values and data tables supply the light palette's required relief.
            ax.annotate(f"{row.co2_low:.1f}", (row.delta_low, y), xytext=(0, 10),
                        textcoords="offset points", ha="center", fontsize=8)
            ax.annotate(f"{row.co2_high:.1f}", (row.delta_high, y), xytext=(0, -15),
                        textcoords="offset points", ha="center", fontsize=8)
        ax.set_yticks(range(len(own)), [FACTOR_NAMES[f] for f in own.factor])
        ax.set_ylim(len(own) - 0.4, -0.7)
        ax.axvline(0, color=LIGHT.text_secondary, lw=1, ls="--")
        ax.set_xlim(-bound, bound)
        ax.set_title(f"{POWERTRAIN_NAMES[powertrain]} | {CYCLES[cycle]}\n"
                     f"Baseline: {own.baseline.iloc[0]:.1f} g CO2/km", loc="left", fontsize=11)
        ax.set_xlabel("Change from baseline in CO2 emissions (g/km)", fontsize=9)
        ax.grid(axis="x", color=LIGHT.grid)
        ax.set_axisbelow(True)
        ax.spines[["top", "right", "left"]].set_visible(False)
    legend = [Line2D([], [], marker=m, color="#52514e", ls="", label=label)
              for m, label in (("o", "Parameter -10%"), ("D", "Parameter +10%"))]
    fig.legend(handles=legend, loc="outside lower center", ncol=2, frameon=False,
               title="Endpoint labels are absolute g CO2/km; factors ranked by endpoint span")
    fig.savefig(path, dpi=180, facecolor=LIGHT.surface)
    fig.savefig(path.with_suffix(".pdf"), facecolor=LIGHT.surface)
    plt.close(fig)


def baseline_table(frame: pd.DataFrame) -> pd.DataFrame:
    baseline = frame[frame.factor == "baseline"]
    table = baseline.pivot(index="powertrain", columns="cycle", values="co2_eu")
    return table.reindex(index=BASE, columns=CYCLES).rename(index=POWERTRAIN_NAMES, columns=CYCLES)


def rank_table(ranked: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for powertrain in BASE:
        for cycle in CYCLES:
            group = ranked[(ranked.powertrain == powertrain) & (ranked.cycle == cycle)]
            top = group.iloc[0]
            rows.append({
                "Car": POWERTRAIN_NAMES[powertrain], "Cycle": CYCLES[cycle],
                "Factors, largest span first": " > ".join(FACTOR_NAMES[f] for f in group.factor),
                "Largest span (g/km)": top.swing,
            })
    return pd.DataFrame(rows)


def feasibility_table(frame: pd.DataFrame) -> pd.DataFrame:
    flagged = frame[frame.short_steps > 0]
    return (flagged.groupby(["powertrain", "cycle"], sort=False)
            .agg(flagged_rows=("short_steps", "size"),
                 maximum_short_steps=("short_steps", "max"),
                 maximum_short_kw=("short_kw", "max")).reset_index())


