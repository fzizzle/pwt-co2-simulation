def slides(directory: Path, frame: pd.DataFrame) -> None:
    from pptx import Presentation
    from pptx.dml.color import RGBColor
    from pptx.util import Inches, Pt

    deck = Presentation()
    deck.slide_width, deck.slide_height = Inches(13.333), Inches(7.5)

    def text(slide, x, y, width, height, content, size=20, colour="0B0B0B"):
        box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(width), Inches(height))
        box.text_frame.word_wrap = True
        for i, line in enumerate(content.split("\n")):
            paragraph = box.text_frame.paragraphs[0] if i == 0 else box.text_frame.add_paragraph()
            paragraph.text = line
            paragraph.font.size = Pt(size)
            paragraph.font.color.rgb = RGBColor.from_string(colour)
            paragraph.space_after = Pt(14)

    def page(title, note):
        slide = deck.slides.add_slide(deck.slide_layouts[6])
        slide.background.fill.solid()
        slide.background.fill.fore_color.rgb = RGBColor.from_string("FCFCFB")
        text(slide, 0.55, 0.25, 12.2, 0.9, title, 29)
        text(slide, 0.55, 6.95, 12.2, 0.35,
             f"Study B | Owner review draft | {len(deck.slides)}/5 | {note}", 10, "52514E")
        return slide

    slide = page("At a fixed driving task, the leading CO2 factor changes by car", "250 g CO2/kWh grid")
    text(slide, 0.7, 1.4, 11.9, 4.9,
         "42 vehicles × 4 cycles = 168 runs; one factor changed by ±10% at a time.\n"
         "Approved choices: car mass alone; peak engine efficiency only; fixed baseline petrol laps.\n"
         "Assignment fleet, storage losses and existing hybrid strategies stay fixed.\n"
         "Rank by |CO2 at +10% − CO2 at −10%|. This is a finite span, not a design optimum.\n"
         "All 16 baselines reproduce the plan to one decimal. Figures, tables and slides regenerate from code.", 23)

    chart_slides = (
        ("Engine efficiency leads petrol and full hybrid on WLTC", "combustion",
         "Fuel divides required engine work by efficiency; scaling the whole curve has a direct effect.\n"
         "Spans: petrol 28.3 and full hybrid 26.0 g/km. Petrol WLTC is already engine-power infeasible."),
        ("BEV shifts from rolling resistance on NEDC to drag on WLTC", "electric",
         "Rolling span: 3.77 g/km on NEDC; drag span: 4.36 g/km on WLTC. Speed raises drag force quadratically.\n"
         "NEDC rolling and mass are close (3.77 versus 3.64); equal parameter ranges are assumptions."),
        ("Mass leads the plug-in hybrid on both fixed laps", "plugin",
         "Mass changes both electric and fuel work; engine efficiency changes only the fuel contribution.\n"
         "Mass spans: eco 23.7 and sport 50.4 g/km. Results depend on the fixed trace and battery start."),
    )
    for title, name, explanation in chart_slides:
        slide = page(title, "Endpoint labels: g CO2/km | Full numbers and flags in the CSVs")
        slide.shapes.add_picture(str(directory / f"study-b-{name}.png"), Inches(0.45),
                                 Inches(1.2), width=Inches(12.4))
        text(slide, 0.65, 5.85, 12.0, 1.0, explanation, 17)

    slide = page("Check feasibility and realistic ranges before choosing a design", "Next: feasible ranges, intermediate points, interactions")
    flagged = int((frame.short_steps > 0).sum())
    text(slide, 0.7, 1.35, 11.9, 5.4,
         f"{flagged} of 168 rows flag engine-power shortfalls. Requested-trace CO2 is not proof a car can follow it.\n"
         "Ratios affect rotating mass and capability; combustion efficiency has no rpm map. BEV efficiency does.\n"
         "An endpoint span can hide curvature: both BEV WLTC gear endpoints are above baseline.\n"
         "Equal ±10% changes are not equally plausible. One-factor runs miss interactions and strategy re-tuning.\n"
         "Next: agree feasible ranges, sample intermediate points, regenerate feasible traces, then test selected interactions.", 22)
    for slide in deck.slides:
        slide.notes_slide.notes_text_frame.text = (
            "Draft for the owner's review and adaptation as personal graded work. "
            "Reproduce with python -m pwt.sensitivity_report. See docs/study-b-sensitivity.md "
            "and the two CSVs for assumptions, exact values, all rankings and feasibility flags."
        )
    deck.save(directory / "study-b-slides.pptx")


def main() -> None:
    frame = sensitivity()
    check_baseline(frame)
    ranked = export(frame)
    for name, selection in PANELS:
        plot(ranked, selection, HERE / f"study-b-{name}.png")
    report = HERE / "study-b-sensitivity.md"
    introduction = report.read_text(encoding="utf-8").split(MARKER)[0].rstrip()
    report.write_text(introduction + "\n\n" + MARKER + "\n\n"
                      + tables_and_findings(frame, ranked) + "\n", encoding="utf-8")
    slides(HERE, frame)
    print("Generated 168 results, 76 ranked spans, three paired PNG/PDF charts, report and five slides.")


if __name__ == "__main__":
    main()
