"""Study C runner: grip and spoiler sweeps on the sport lap.

    python -m pwt.study_c      # write docs/study-c-results.md and the two figures

Every number marked ASSUMPTION is a choice recorded in docs/study-c-cornering.md.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from pwt.cornering import downforce_speed, grip_speed
from pwt.model import fleet
from pwt.model.profile import generate, lap_time_s
from pwt.sweep import sweep

DOCS = Path(__file__).resolve().parent.parent / "docs"
MU0 = 0.7            # course sheet "11 Good trajectory speed": gamma = 0.7 g
LD = 4.0             # ASSUMPTION: spoiler lift-to-drag ratio (added SCz / added SCx)
KG_PER_SCZ = 40.0    # ASSUMPTION: added mass, kg per m2 of SCz (0.2 m2 -> 8 kg)
GRIPS = (0.9, 1.0, 1.1, 1.2, 1.3)
SCZS = (0.0, 0.1, 0.2, 0.3, 0.4)
CARS = {
    "petrol": fleet.petrol,
    "electric": fleet.electric,
    "hybrid": lambda: fleet.hybrid(0.6),
    "plugin": lambda: fleet.plugin(0.98),
}
KEY = "franco_sport_generated"


def spoiler_car(car, scz):
    return replace(
        car,
        cx=car.cx + scz / LD / car.frontal_area,
        m_vehicle=car.m_vehicle + KG_PER_SCZ * scz,
    )


def run() -> pd.DataFrame:
    """Each lap is generated by the petrol car (as in pwt.sweep.cycles) and driven by every car."""
    rows = []
    petrol = fleet.petrol()
    cars = {name: make() for name, make in CARS.items()}

    def record(kind, x, lap, variants):
        t = sweep(variants, {KEY: lap})
        for _, r in t.iterrows():
            rows.append(dict(car=r.powertrain, kind=kind, x=x, lap_s=lap_time_s(lap),
                             co2_eu=r.co2_eu, short=r.short_steps))

    for g in GRIPS:
        lap = generate("sport", petrol, corner_speed=grip_speed(g))
        record("tyres", g, lap, {(n, "grip", g): c for n, c in cars.items()})
    for scz in SCZS:
        sp = spoiler_car(petrol, scz)
        lap = generate("sport", sp, corner_speed=downforce_speed(MU0, scz, sp.m_total))
        record("spoiler", scz, lap, {(n, "spoiler", scz): spoiler_car(c, scz)
                                     for n, c in cars.items()})
    return pd.DataFrame(rows)


def figures(df: pd.DataFrame) -> None:
    for col, label, fname in (("lap_s", "Lap time (s)", "study-c-lap-time.png"),
                              ("co2_eu", "g CO2/km (EU grid)", "study-c-co2.png")):
        fig, axes = plt.subplots(1, 2, figsize=(9, 3.6))
        for ax, kind, xl in zip(axes, ("tyres", "spoiler"),
                                ("Grip factor", "Spoiler SCz (m2)")):
            for car, d in df[df.kind == kind].groupby("car"):
                ax.plot(d.x, d[col], marker="o", label=car)
            ax.set_xlabel(xl)
            ax.set_ylabel(label)
            ax.set_title(kind)
        axes[0].legend()
        fig.tight_layout()
        fig.savefig(DOCS / fname, dpi=130)
        plt.close(fig)


if __name__ == "__main__":
    df = run()
    figures(df)
    (DOCS / "study-c-results.md").write_text(df.round(2).to_markdown(index=False) + "\n")
    print(df.round(2).to_string())
