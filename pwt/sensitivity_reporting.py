FACTOR_NAMES = {"mass": "Car mass", "drag": "Drag coefficient", "rolling": "Rolling resistance",
                "gears": "Gear ratios", "engine": "Peak engine efficiency"}
TIE_FRACTION = 0.02
MARKER = "<!-- Generated by python -m pwt.sensitivity_report; edit the generator below this point. -->"
PANELS = (
    ("combustion", (("petrol", "wltc"), ("hybrid", "wltc"))),
    ("electric", (("bev", "nedc"), ("bev", "wltc"))),
    ("plugin", (("phev", "franco_eco_generated"), ("phev", "franco_sport_generated"))),
    ("provisional", (("petrol", "franco_eco_generated"), ("petrol", "franco_sport_generated"))),
)


def near_tie(a, b):
    return a == b or abs(a-b) < TIE_FRACTION * max(abs(a), abs(b))


def ranking_text(group):
    """Anchor ties to their largest span; do not chain near-ties transitively."""
    parts, anchor = [], None
    for row in group.sort_values(["swing", "factor"], ascending=[False, True]).itertuples():
        tied = anchor is not None and near_tie(anchor, row.swing)
        if parts:
            parts.append(" ≈ " if tied else " > ")
        if not tied:
            anchor = row.swing
        parts.append(FACTOR_NAMES[row.factor] + (" †" if not row.engine_check_pass else ""))
    return "".join(parts) or "No comparison passes the engine check"


def rank_table(ranked):
    rows = []
    for (p, c), group in ranked.groupby(["powertrain", "cycle"], sort=False):
        rows.append({"Car": POWERTRAIN_NAMES[p], "Cycle": CYCLES[c],
                     "Requested trace": ranking_text(group),
                     "Passing baseline and both endpoints": ranking_text(group[group.engine_check_pass])})
    return pd.DataFrame(rows)


def result_facts(frame, ranked):
    """One numerical source for both the report and PowerPoint; no typed-in results."""
    lookup = ranked.set_index(["powertrain", "cycle", "factor"])
    def span(p, c, f, places=2):
        return f"{lookup.loc[(p,c,f), 'swing']:.{places}f}"
    def leaders(p, c):
        own = ranked[(ranked.powertrain == p) & (ranked.cycle == c)]
        top = own.swing.max()
        return " ≈ ".join(FACTOR_NAMES[r.factor] for r in own.itertuples() if near_tie(top, r.swing))
    p = lookup.loc[("petrol", "wltc", "engine")]
    h = lookup.loc[("hybrid", "wltc", "engine")]
    wd, wm = (lookup.loc[("phev", "wltc", f)] for f in ("drag", "mass"))
    bg = lookup.loc[("bev", "wltc", "gears")]
    hg = lookup.loc[("hybrid", "franco_sport_generated", "gears")]
    return {
        "combustion_title": f"WLTC leaders: petrol {leaders('petrol','wltc')}; hybrid {leaders('hybrid','wltc')}",
        "combustion": f"WLTC engine-efficiency spans: petrol {p.swing:.1f} and full hybrid {h.swing:.1f} g/km "
                      f"({h.swing_percent:.1f}% of the hybrid baseline). Fuel demand divides engine work by efficiency. "
                      "Scaling eta_max changes the whole power curve; idle fuel is fixed. A large effect does not establish low cost.",
        "electric_title": f"BEV leaders: NEDC {leaders('bev','nedc')}; WLTC {leaders('bev','wltc')}",
        "electric": f"BEV NEDC rolling and mass spans: {span('bev','nedc','rolling')} and {span('bev','nedc','mass')} g/km; "
                    f"WLTC drag span: {span('bev','wltc','drag')} g/km. Drag force grows with speed squared; mass affects "
                    "acceleration, rolling and climbing work, with partial recovery. Small gaps require caution.",
        "plugin_title": f"PHEV lap leaders: eco {leaders('phev','franco_eco_generated')}; sport {leaders('phev','franco_sport_generated')}",
        "plugin": f"PHEV mass spans: eco {span('phev','franco_eco_generated','mass',1)} and "
                  f"sport {span('phev','franco_sport_generated','mass',1)} g/km. Mass affects both electric and fuel "
                  "work; engine efficiency affects fuel conversion. Regulatory results include R101 weighting.",
        "near_tie": f"PHEV WLTC drag and mass spans: {wd.swing:.3f} and {wm.swing:.3f} g/km; "
                    f"gap {abs(wd.swing-wm.swing):.3f} g/km. The ranking table applies the stated tie rule.",
        "gears": f"BEV WLTC gear endpoint deltas: {bg.delta_low:+.3f} and {bg.delta_high:+.3f} g/km "
                 f"(span {bg.swing:.3f}). Hybrid sport gear deltas: {hg.delta_low:+.3f} and {hg.delta_high:+.3f}. "
                 "A small endpoint span can hide curvature. Combustion efficiency is power-based; the BEV motor "
                 "map also depends on rpm. The intermediate points test this without claiming a continuous optimum.",
        "flagged": int((frame.short_steps > 0).sum()), "runs": len(frame),
    }


def plot(ranked, selection, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    from dashboard.theme import LIGHT

    fig, axes = plt.subplots(1, 2, figsize=(13, 5.3), layout="constrained")
    selected = pd.concat([ranked[(ranked.powertrain == p) & (ranked.cycle == c)] for p,c in selection])
    bound = max(selected[["delta_low", "delta_high"]].abs().to_numpy().max()*1.25, 0.1)
    for ax, (p, c) in zip(axes, selection):
        own = ranked[(ranked.powertrain == p) & (ranked.cycle == c)].sort_values("rank")
        colour = LIGHT.for_powertrain(p)
        for y, row in enumerate(own.itertuples()):
            low, high = sorted((row.delta_low, row.delta_high))
            ax.barh(y, high-low, left=low, height=0.5, color=colour, alpha=0.75,
                    hatch="//" if not row.engine_check_pass else None)
            for suffix, marker, dy in (("low","o",10), ("high","D",-15)):
                ax.scatter(getattr(row,f"delta_{suffix}"), y, marker=marker, s=48, zorder=3,
                           facecolors="white" if getattr(row,f"short_steps_{suffix}") > 0 else colour,
                           edgecolors=LIGHT.text_primary, linewidths=1)
                ax.annotate(f"{getattr(row,f'co2_{suffix}'):.1f}",
                            (getattr(row,f"delta_{suffix}"), y), xytext=(0,dy),
                            textcoords="offset points", ha="center", fontsize=8)
        ax.set_yticks(range(len(own)), [FACTOR_NAMES[f] for f in own.factor])
        ax.set_ylim(len(own)-0.4, -0.7)
        ax.axvline(0, color=LIGHT.text_secondary, lw=1, ls="--")
        ax.set_xlim(-bound, bound)
        warning = " | baseline fails engine check" if own.baseline_short_steps.iloc[0] else ""
        ax.set_title(f"{POWERTRAIN_NAMES[p]} | {CYCLES[c]}\nBaseline {own.baseline.iloc[0]:.1f} g CO2/km{warning}",
                     loc="left", fontsize=9)
        ax.set_xlabel("Change from baseline in CO2 emissions (g/km)", fontsize=9)
        ax.grid(axis="x", color=LIGHT.grid)
        ax.set_axisbelow(True)
        ax.spines[["top","right","left"]].set_visible(False)
    legend = [Line2D([],[],marker=m,color="#52514e",ls="",label=label)
              for m,label in (("o","Parameter -10%"),("D","Parameter +10%"))]
    legend.append(Line2D([],[],marker="o",markerfacecolor="white",color="#52514e",ls="",
                         label="Hollow: endpoint fails engine check"))
    fig.legend(handles=legend,loc="outside lower center",ncol=3,frameon=False,fontsize=9,
               title="Labels: absolute g CO2/km | Hatched: baseline or an endpoint fails engine check")
    fig.savefig(path,dpi=180,facecolor=LIGHT.surface)
    fig.savefig(path.with_suffix(".pdf"),facecolor=LIGHT.surface)
    plt.close(fig)


def endpoint_comparison(frame):
    rows = []
    for (p,c), group in frame.groupby(["powertrain","cycle"],sort=False):
        baseline = group[group.factor == "baseline"].iloc[0]
        for factor, endpoints in group[group.factor != "baseline"].groupby("factor"):
            ends = endpoints.set_index("scale")
            rows.append({"powertrain":p,"cycle":c,"factor":factor,
                         "swing":abs(ends.loc[1.1,"co2_eu"]-ends.loc[0.9,"co2_eu"]),
                         "engine_check_pass":baseline.short_steps == 0 and (ends.short_steps == 0).all()})
    return pd.DataFrame(rows)


def extension_sections(extra, ranked):
    gear_rows, mass_rows, curve_rows, range_rows = [], [], [], []
    for (p,c), group in extra["intermediate"].groupby(["powertrain","cycle"],sort=False):
        sample = group[group.factor.isin(["gears","baseline"])]
        best = sample.loc[sample.co2_eu.idxmin()]
        baseline = group[group.factor == "baseline"].co2_eu.iloc[0]
        gear_rows.append({"Car":p,"Cycle":c,"Best sampled ratio scale":best.scale,
                          "Change (g/km)":best.co2_eu-baseline,"Short steps":best.short_steps})
    for (p,c), group in extra["assumptions"].groupby(["powertrain","cycle"],sort=False):
        spans = {e:group[group.experiment == e].co2_eu.max()-group[group.experiment == e].co2_eu.min()
                 for e in ("body_mass","total_mass")}
        changed = ranked[(ranked.powertrain == p) & (ranked.cycle == c)].copy()
        changed.loc[changed.factor == "mass","swing"] = spans["total_mass"]
        changed.loc[changed.factor == "mass","engine_check_pass"] = (
            group[group.experiment.isin(["baseline","total_mass"])].short_steps == 0).all()
        mass_rows.append({"Car":p,"Cycle":c,"Body span":spans["body_mass"],"Total span":spans["total_mass"],
                          "Total-mass ranking":ranking_text(changed)})
        baseline = group[group.experiment == "baseline"].co2_eu.iloc[0]
        for row in group[group.experiment.isin(["shape_only","workbook_curve"])].itertuples():
            curve_rows.append({"Car":p,"Cycle":c,"Experiment":row.experiment,"Curve":row.setting,
                               "Change (g/km)":row.co2_eu-baseline,"Short steps":row.short_steps})
    for (p,c,factor), group in extra["ranges"].groupby(["powertrain","cycle","factor"],sort=False):
        if factor == "baseline":
            continue
        baseline = extra["ranges"].query("powertrain == @p and cycle == @c and factor == 'baseline'").iloc[0]
        for row in group.itertuples():
            range_rows.append({"Car":p,"Cycle":c,"Factor":factor,"Scale":row.scale,
                               "CO2 saving (g/km)":baseline.co2_eu-row.co2_eu,
                               "Engine check passes":baseline.short_steps == 0 and row.short_steps == 0})
    ranges = pd.DataFrame(range_rows)
    passing = ranges[ranges["Engine check passes"]]
    best = passing.loc[passing.groupby(["Car","Cycle"])["CO2 saving (g/km)"].idxmax()]
    regen_rows, changed_leaders = [], []
    for (p,c), group in endpoint_comparison(extra["regenerated"]).groupby(["powertrain","cycle"],sort=False):
        fixed = ranked[(ranked.powertrain == p) & (ranked.cycle == c)]
        passing_group = group[group.engine_check_pass]
        regen_rows.append({"Car":p,"Cycle":c,"Fixed trace":ranking_text(fixed),
                           "Regenerated, passing comparisons":ranking_text(passing_group)})
        if not passing_group.empty:
            old_leader = fixed.loc[fixed.swing.idxmax(),"factor"]
            new_leader = passing_group.loc[passing_group.swing.idxmax(),"factor"]
            if old_leader != new_leader:
                changed_leaders.append(f"{POWERTRAIN_NAMES[p]} on {CYCLES[c]}: "
                                       f"{FACTOR_NAMES[old_leader]} → {FACTOR_NAMES[new_leader]}")
    interactions = []
    for (p,c,factor), group in extra["interactions"].groupby(["powertrain","cycle","second_factor"],sort=False):
        passing = group[group.engine_check_pass]
        interactions.append({"Car":p,"Cycle":c,"Pair":f"mass × {factor}",
                             "Largest |interaction| (g/km)":group.interaction_g_km.abs().max(),
                             "Largest passing |interaction|":passing.interaction_g_km.abs().max(),
                             "Failing points":int((~group.engine_check_pass).sum())})
    curve_summary = pd.DataFrame(curve_rows)
    shapes = curve_summary[curve_summary.Experiment == "shape_only"]
    largest_shape = shapes.loc[shapes["Change (g/km)"].abs().idxmax()]
    gear_summary = pd.DataFrame(gear_rows)
    gear_improved = gear_summary[gear_summary["Change (g/km)"] < -1e-8]
    return "\n\n".join([
        "## Research extensions (exploratory)\n\nThese supplement the approved fixed-trace study. "
        "They do not establish a re-tuned design, achievable technology package or economic optimum.",
        "### Intermediate points and gear curvature\n\nAll factors add ±5%; gears also add ±2.5% and ±7.5%. "
        "Scale 1.0 is the baseline. The lowest sampled gear result below includes flagged points explicitly; "
        "it establishes neither a continuous minimum nor a feasible optimum. Full points: "
        "[intermediate CSV](study-b-intermediate.csv). "
        f"A sampled gear setting improves on baseline in {len(gear_improved)} of {len(gear_summary)} car/cycle "
        "combinations, before feasibility filtering. The table retains the exact sampled scales and flags.\n\n"
        + gear_summary.to_markdown(index=False,floatfmt=".4f"),
        "### Total mass versus body mass\n\nThe alternative changes body mass enough to move total mass by ±10%, "
        "keeping driver, machine, battery and capacities fixed. It is a stronger body perturbation for electrified "
        "cars, not a physical lightweighting design. Only the mass span is replaced in the ranking (g/km).\n\n"
        + pd.DataFrame(mass_rows).to_markdown(index=False,floatfmt=".3f"),
        "### Engine curve shape\n\nMenus in workbooks 10, 15 and 35 are read by label and verified to agree. "
        "`shape_only` retains the assignment eta_max multiplier and changes a1/a2/a3; `workbook_curve` also "
        "uses the menu's eta_max. The old-engine peak change is thereby separated from the part-load shape. "
        "These categorical alternatives are not ±10% changes and cannot be inserted in the equal-range ranking. "
        "Deltas test the engine response beyond height scaling; they do not establish a universal ranking. "
        f"The largest absolute shape-only delta is {largest_shape['Change (g/km)']:+.3f} g/km "
        f"for {largest_shape.Car}, {largest_shape.Cycle}, {largest_shape.Curve}. "
        "The normalized demand P/Pmax samples different portions of the polynomial on different cycles; "
        "a curve name alone is not evidence of an efficiency improvement.\n\n"
        + extra["curves"].to_markdown(index=False,floatfmt=".4f") + "\n\n"
        + pd.DataFrame(curve_rows).to_markdown(index=False,floatfmt=".3f"),
        "### Technology-inspired improvement ranges\n\nBody mass −5%/−10%; drag −10%/−20%; rolling −10%/−20%; "
        "engine eta_max +5%/+10%; gears −5%/+5%. DOE lightweighting and EPA's 2016 technology assessment "
        "motivate the road-load ranges ([sources](sources.md#study-b-extension-ranges)). The translation from "
        "vehicle mass to body mass and both engine increments are study assumptions; engine multipliers "
        "remain inside the assignment's 20–40% range. Gear increments have no sourced universal feasible range "
        "and are explicitly exploratory. These are screening ranges, not validated achievable limits for these "
        "cars, a symmetric uncertainty interval or a cost ranking. No tyre-grip, safety, cost or re-tuning model "
        "is available. The largest sampled saving among scenarios passing the engine check is shown per "
        "car/cycle; groups with a failing baseline are omitted. All endpoints: [ranges CSV](study-b-ranges.csv).\n\n"
        + best.to_markdown(index=False,floatfmt=".3f"),
        "### Per-vehicle regenerated laps\n\nEvery petrol/hybrid variant receives its own generated lap and "
        "gears, then the engine shortfall check. Speed and lap time change with CO2, so the driving task differs. "
        "Hybrids use the generator's combustion-engine-only acceleration envelope, not optimal combined power. "
        "Only comparisons whose baseline and both endpoints pass are ranked below; this does not establish full "
        "vehicle feasibility. BEV regeneration is omitted because the shared generator lacks its motor/battery "
        "capability model. CSV rows retain lap time and residual shortfalls.\n\n"
        + ("Changes in the strictly highest-span factor: " + "; ".join(changed_leaders) + ". "
           "This shows sensitivity to the driving-task assumption; it is not an independent technology benefit.\n\n"
           if changed_leaders else "The strictly highest-span factor is unchanged in the passing regenerated comparisons.\n\n")
        + pd.DataFrame(regen_rows).to_markdown(index=False),
        "### Two-factor interactions\n\nA 3×3 grid (0.9, 1.0, 1.1) tests mass × drag and mass × gears for all "
        "powertrains, plus mass × engine efficiency for hybrids, on WLTC and sport. Interaction = "
        "C(m,x) − C(m,1) − C(1,x) + C(1,1), in g/km; zero is additive at that sampled point. Passing requires "
        "all four terms to pass the engine check; NaN means none passed. Original traces and strategies stay fixed.\n\n"
        + pd.DataFrame(interactions).to_markdown(index=False,floatfmt=".3f"),
    ])


