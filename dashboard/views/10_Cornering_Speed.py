"""Study C report: tyre grip and spoiler downforce on the Spa sport lap."""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import pandas as pd
import streamlit as st

from dashboard.cornering_charts import (
    CO2, VARIANTS, baseline_row, comparison_table, infeasible, line_chart, rows_for,
)
from dashboard.layout import configure, download
from pwt.catalog import POWERTRAIN_NAMES
from pwt.sweep import CYCLES

DOCS = ROOT / "docs"
LAP = "franco_sport_generated"
pal = configure("Cornering speed")


@st.cache_data(show_spinner=False)
def read_table(filename: str, modified_ns: int) -> pd.DataFrame:
    return pd.read_csv(DOCS / filename)


def table(name: str) -> pd.DataFrame:
    filename = f"study-c-{name}.csv"
    return read_table(filename, (DOCS / filename).stat().st_mtime_ns)


def render_report(text: str) -> None:
    """Render local report figures inline; downloads provide its referenced artifacts."""
    parts = re.split(r"!\[([^\]]*)\]\(([^)]+)\)", text)
    for index in range(0, len(parts), 3):
        # Repo-relative documents are downloads below, not URLs on the Streamlit server.
        markdown = re.sub(r"\[([^\]]+)\]\((?!https?://)[^)]+\)", r"\1", parts[index])
        st.markdown(markdown)
        if index + 2 < len(parts):
            path = (DOCS / parts[index + 2]).resolve()
            if path.parent == DOCS.resolve() and path.is_file():
                st.image(str(path), caption=parts[index + 1], width="stretch")


st.title("Study C · Cornering speed")
st.markdown("Change the tyre grip, or add a spoiler with its drag and mass, and see how the "
            "lap time and CO₂ of the Spa sport lap respond.")
st.caption("Owner-review draft · Assignment vehicles · Storage losses included · Saved study results")

try:
    results = table("results")
except (FileNotFoundError, pd.errors.EmptyDataError):
    st.error("The saved Study C results are missing. Restore the study files before opening this page.")
    st.stop()

left, middle, right = st.columns(3)
powertrain = left.selectbox("Car", list(POWERTRAIN_NAMES), format_func=POWERTRAIN_NAMES.get,
                           key="study_c_powertrain")
variant = middle.selectbox("Change", list(VARIANTS), format_func=lambda v: VARIANTS[v][2],
                           key="study_c_variant")
grid = right.selectbox("Electricity grid", list(CO2), format_func=CO2.get, key="study_c_grid")
middle.caption(f"Driving cycle: {CYCLES[LAP]}")

rows = rows_for(results, powertrain, variant)
baseline = baseline_row(results, powertrain)

explore, report_tab = st.tabs(["Explore", "Full report & downloads"])
with explore:
    st.subheader(f"{POWERTRAIN_NAMES[powertrain]} · {CYCLES[LAP]}")
    a, b = st.columns(2)
    a.metric("Baseline lap time", f"{baseline.lap_time_s:.1f} s")
    b.metric("Baseline emissions", f"{baseline[grid]:.1f} g CO₂/km")
    if baseline.short_steps:
        st.warning(f"The baseline cannot follow this lap on {int(baseline.short_steps)} steps "
                   f"(shortfall up to {baseline.short_kw:.2f} kW). All results below are provisional.")
    elif infeasible(rows).any():
        st.warning("Some variants cannot follow their lap. Their rows are marked as provisional "
                   "and drawn with hollow markers.")
    st.plotly_chart(line_chart(rows, variant, "lap_time_s", "Lap time (s)", powertrain, pal),
                    width="stretch", theme=None)
    st.plotly_chart(line_chart(rows, variant, grid, "CO₂ emissions (g CO₂/km)", powertrain, pal),
                    width="stretch", theme=None)
    st.caption("Hollow markers cannot follow the lap at the engine's full-load power (provisional).")
    numbers = comparison_table(rows, variant, grid)
    st.dataframe(numbers, width="stretch", hide_index=True)
    download(numbers, f"pwt-study-c-{powertrain}-{variant}.csv", "Download this comparison")
    with st.expander("How to read the study", expanded=False):
        st.markdown("- **Radii** are inferred or estimated from a coarse outline.\n"
                    "- **One line:** the model has one line through each corner.\n"
                    "- **Fixed braking:** the sport lap brakes at 0.6 g; more grip may also allow harder braking.\n"
                    "- **Fixed speeds elsewhere:** only the listed corners change.")
        st.markdown("Each lap is generated by the petrol car, as in the other studies, and driven by every car. "
                    "The spoiler variants carry their added drag and mass in both the lap and the car.")
        st.markdown("The grip and spoiler values are the owner's assumptions; see the full report.")

with report_tab:
    st.subheader("Report and evidence")
    st.markdown("The written report covers all cars regardless of the selections above.")
    report_path = DOCS / "study-c-cornering.md"
    if report_path.exists():
        with st.expander("Read the full Study C report"):
            render_report(report_path.read_text(encoding="utf-8"))
    files = sorted(path for path in DOCS.glob("study-c-*") if path.suffix in (".md", ".csv", ".png"))
    files.append(DOCS / "sources.md")
    artifact = st.selectbox("Download a study artifact", files, format_func=lambda path: path.name,
                            key="study_c_artifact")
    st.download_button("Download selected artifact", artifact.read_bytes(), file_name=artifact.name,
                       key="study_c_download")
    st.caption("Interpretation and slides remain an owner-review draft.")
